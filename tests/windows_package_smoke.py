"""Run on a Windows CI host. Does not launch or modify Antigravity."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    archive = Path(sys.argv[1])
    target = ROOT / 'work' / 'Windows 中文 & 空格'
    target.mkdir(parents=True)
    with zipfile.ZipFile(archive) as z:
        z.extractall(target)  # This ZIP was generated by package_windows.py in CI.
    folder, = [p for p in target.iterdir() if p.is_dir()]
    manifest = json.loads((folder / 'PACKAGE-SHA256.json').read_text(encoding='utf-8'))
    for name, expected in manifest.items():
        assert hashlib.sha256((folder / name).read_bytes()).hexdigest() == expected, name
    runtime = folder / 'runtime/python.exe'
    result = subprocess.run([str(runtime), '-I', '-X', 'utf8', '-m', 'unittest', 'discover',
                             '-s', 'tests', '-p', 'test_windows_patcher.py'], cwd=folder,
                            capture_output=True, text=True, encoding='utf-8')
    print(result.stdout)
    print(result.stderr)
    assert result.returncode == 0, 'Embedded Python tests failed'
    result = subprocess.run(['cmd', '/d', '/c', str(folder / 'Windows-Start.cmd'), '--help'],
                            cwd=folder, input='\n', capture_output=True, text=True, encoding='utf-8')
    print(result.stdout)
    print(result.stderr)
    assert result.returncode == 0 and 'Windows 11 x64' in result.stdout, 'CMD launcher failed'
    print('Windows package contents, embedded runtime and CMD launcher: PASS')


if __name__ == '__main__':
    main()
